// Время и дата: отвечает компьютер, а не поисковик.
//
// Проверка нужна потому, что промах здесь выглядел как поломка модели. Слова
// «сейчас» и «сегодня» ведут прямиком в признак «нужны свежие сведения», поиск
// показывал «ищу в интернете», тратил секунды и приносил страницы «точное
// время» вместо самого времени — а модель, ничего о часах не знающая, честно
// отвечала, что доступа к такой информации у неё нет.
//
// Здесь проверяется обе половины починки: что часы попадают в подсказку и что
// вопрос о них больше не уходит в поиск — но только тот, на который часы
// компьютера действительно отвечают.
import 'package:anima/main.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  final web = WebSearchService.instance;

  group('вопрос к часам компьютера', () {
    for (final q in const [
      'сколько сейчас времени',
      'Сколько времени?',
      'который час',
      'Который сейчас час?',
      'какое сегодня число',
      'какое число сегодня?',
      'какой сегодня день недели',
      'какая сегодня дата',
      'what time is it',
      'What time is it now?',
      'what is the current date',
      'what day is today',
    ]) {
      test('«$q» — без поиска', () {
        expect(web.isClockQuestion(q), isTrue);
      });
    }
  });

  group('а это по-прежнему в поиск', () {
    for (final q in const [
      // Чужой часовой пояс из местных часов не выводится.
      'сколько времени в Токио',
      'какое сегодня число по лунному календарю',
      // Обычные «свежие» вопросы задеть не должно.
      'какая сейчас погода',
      'курс доллара сегодня',
      'какое сегодня событие в новостях',
    ]) {
      test('«$q»', () {
        expect(web.isClockQuestion(q), isFalse);
      });
    }
  });

  test('часы попадают в подсказку модели', () {
    final now = DateTime.now();
    final block = animaNowBlock();
    expect(block, contains('${now.year}-'));
    expect(block, contains(now.hour.toString().padLeft(2, '0')));
    // Смысл блока в том, чтобы модель им пользовалась, а не пересказывала.
    expect(block.toLowerCase(), contains('current local time'));
  });
}
