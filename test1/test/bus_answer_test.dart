// Разбор ответа «да/нет» на вопрос шины.
//
// Проверка нужна потому, что ошибка здесь не видна: ассистент спросил,
// человек ответил, и звук либо уехал в наушники без спроса, либо остался в
// колонках вопреки согласию. И то и другое выглядит как «показалось».
import 'package:anima/main.dart';
import 'package:flutter_test/flutter_test.dart';

bool? answer(String s) => VoiceAssistant.busAnswerOf(s);

void main() {
  test('согласие', () {
    for (final s in ['да', 'ага', 'давай', 'конечно', 'ок', 'хорошо',
                     'переключи', 'переключай', 'да переключи']) {
      expect(answer(s), true, reason: s);
    }
  });

  test('отказ', () {
    for (final s in ['нет', 'неа', 'не надо', 'не нужно', 'потом', 'отмена',
                     'оставь']) {
      expect(answer(s), false, reason: s);
    }
  });

  test('отказ сильнее согласия', () {
    // «не переключай» начинается с «не» и содержит «переключай»: победить
    // должен отказ, иначе фраза сработает ровно наоборот сказанному.
    expect(answer('не переключай'), false);
    expect(answer('не надо переключать'), false);
  });

  test('целым словом, а не куском', () {
    // «недавно» начинается с «не», но ответом не является: съев его, шина
    // молча отказалась бы за человека.
    expect(answer('недавно я это уже делал'), null);
    expect(answer('дай мне минуту'), null);
    expect(answer('нетбук завис'), null);
  });

  test('не ответ — значит не ответ', () {
    expect(answer('какая сейчас погода'), null);
    expect(answer('громкость на 30'), null);
    expect(answer(''), null);
  });
}
