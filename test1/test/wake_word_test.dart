// Разбор слова-активатора: что считается обращением к ассистенту, а что нет.
//
// Случаи взяты из журнала команд за вечер, когда владелец играл с друзьями:
// ассистент вслух отвечал «команда не найдена» на реплики, к нему не
// обращённые. Причина была в одном условии — начало слова-активатора
// принималось за само слово, и «ай» становилось «Айрис».
import 'package:evs/main.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  group('чужая речь не считается обращением', () {
    test('начало имени — не имя', () {
      // Ровно эти две фразы прошли у пользователя и взвели окно команды.
      expect(wakeWordRemainder('ай векарту', 'Айрис'), isNull);
      expect(wakeWordRemainder('ай ну ты скриншите чем', 'Айрис'), isNull);
    });

    test('одиночное «а» тоже не имя', () {
      // «а» -> «a», а «Айрис» -> «airis»: раньше проходило по префиксу.
      expect(wakeWordRemainder('а что там', 'Айрис'), isNull);
      expect(wakeWordRemainder('а ты уверен', 'Айрис'), isNull);
    });

    test('обычная реплика без имени', () {
      expect(wakeWordRemainder('там трое похуй тогда', 'Айрис'), isNull);
      expect(wakeWordRemainder('понял', 'Айрис'), isNull);
    });
  });

  group('настоящие обращения проходят', () {
    test('имя и команда', () {
      expect(wakeWordRemainder('айрис пауза', 'Айрис'), 'пауза');
    });

    test('голое имя — пустой остаток, не null', () {
      expect(wakeWordRemainder('айрис', 'Айрис'), '');
    });

    test('имя с падежным хвостом', () {
      expect(wakeWordRemainder('айрисом', 'Айрис'), isNotNull);
    });

    test('имя расслышано неточно', () {
      // Так распознаватель писал имя в журнале на самом деле.
      expect(wakeWordRemainder('арис паузу', 'Айрис'), 'паузу');
      expect(wakeWordRemainder('айдис', 'Айрис'), isNotNull);
    });
  });

  group('аббревиатура как активатор', () {
    // Ради этого случая мягкость и вводилась: короткое «EVS» распознаётся
    // то как «евс», то как три отдельных слова. Ужесточение не должно его
    // сломать — это значение по умолчанию у всех остальных.
    test('слитно', () {
      expect(wakeWordRemainder('евс пауза', 'EVS'), 'пауза');
    });

    test('по буквам', () {
      expect(wakeWordRemainder('и в эс пауза', 'EVS'), 'пауза');
    });
  });
}
