import 'package:flutter/material.dart';

/// Дерево настроек: раздел → страница → карточка → строка.
/// Перенесено из константы SET в прототипе, без сокращений.

enum RowKind { toggle, segmented, slider, text, value, button, hotkey, area }

class SetRow {
  const SetRow(this.kind, this.name, {this.sub = '', this.key, this.options = const [],
    this.value, this.min = 0, this.max = 100, this.step = 1, this.unit = '', this.decimals = 0,
    this.button, this.danger = false});

  final RowKind kind;
  final String name, sub, unit;
  final String? key, button;
  final List<String> options;
  final Object? value;
  final double min, max, step;
  final int decimals;
  final bool danger;
}

/// Особые карточки, которые рисуются не строками, а своим содержимым.
enum CardKind { rows, models, appearance, widget, log }

class ModelItem {
  const ModelItem(this.name, this.sub, this.size, this.status, this.action);
  final String name, sub, size, status, action;

  Color statusColor(Color ok, Color accent, Color faint) =>
      status == 'Активна' ? ok : status == 'Установлена' ? accent : faint;
}

class SetCard {
  const SetCard(this.title, {this.rows = const [], this.kind = CardKind.rows, this.items = const []});
  final String title;
  final List<SetRow> rows;
  final CardKind kind;
  final List<ModelItem> items;
}

class SetPage {
  const SetPage(this.id, this.title, this.cards);
  final String id, title;
  final List<SetCard> cards;
}

class SetSection {
  const SetSection(this.id, this.title, this.subtitle, this.icon, this.pages);
  final String id, title, subtitle;
  final IconData icon;
  final List<SetPage> pages;
}

// Короткие конструкторы — как T/G/L/X/V/B/K/A в прототипе.
SetRow _t(String k, String n, String s, bool v) => SetRow(RowKind.toggle, n, sub: s, key: k, value: v);
SetRow _g(String k, String n, String s, List<String> o, [String? v]) =>
    SetRow(RowKind.segmented, n, sub: s, key: k, options: o, value: v ?? o.first);
SetRow _l(String k, String n, String s, double min, double max, double st, double v,
        [String unit = '', int d = 0]) =>
    SetRow(RowKind.slider, n, sub: s, key: k, min: min, max: max, step: st, value: v, unit: unit, decimals: d);
SetRow _x(String k, String n, String s, String v) => SetRow(RowKind.text, n, sub: s, key: k, value: v);
SetRow _v(String n, String s, String v) => SetRow(RowKind.value, n, sub: s, value: v);
SetRow _b(String n, String s, String b, [bool dg = false]) => SetRow(RowKind.button, n, sub: s, button: b, danger: dg);
SetRow _k(String n, String s, String v) => SetRow(RowKind.hotkey, n, sub: s, value: v);
SetRow _a(String k, String n, String s, String v) => SetRow(RowKind.area, n, sub: s, key: k, value: v);

